"""The Python pins, kept moving: what each hash-locked list in packaging/ would lock if every pin moved to its newest
release at least two weeks old, worked out by uv itself, and a mode that moves them.

Dependabot can't lock these lists. Each requirements*.txt is `uv pip compile --universal`: every platform's packages
in one file, with hashes. Dependabot's pip support locks with pip-compile, for the one platform it runs on, and its
uv support covers only uv.lock. So this does that job here, and .github/workflows/pins.yml runs it every week.

For each packaging/requirements*.in and the .txt locked from it, uv runs the command at the top of the .txt, in a
folder of its own, on a copy of the .in with every pin's version taken off (its environment marker kept), taking
only files uploaded before the cutoff, 14 days back (CONTRIBUTING.md's cooldown). The new lock is then set against
the old one, name==version by name==version. Four rules hold on the way:

- SKIP below names releases nothing moves to, each with its reason;
- PyQt6 and PyQt6-Qt6 move together, onto one release line (6.11.0 with 6.11.2), or stay where they are;
- a package in more than one lock is at one version in all of them (tests/test_requirements.py): where two locks
  would differ, every lock takes the older;
- nothing moves backwards: a package locked now at a release newer than the cutoff (a security fix, say) stays.

usage:
    python packaging/pins.py [--report FILE]               what can move, as Markdown
    python packaging/pins.py --apply [--cutoff TIMESTAMP]  move it: the .in pins, pyproject.toml's dev extra, and
                                                           each lock, locked again with its own header's command

--cutoff repeats a report's cutoff, so --apply moves exactly what that report listed. Exit codes: 0, nothing can
move (or --apply moved it); 3, something can move; 2, an error. It reaches the network only through uv, and needs
no credentials.
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
import tomllib
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import NamedTuple

ROOT = Path(__file__).resolve().parent.parent
COOLDOWN = dt.timedelta(days=14)  # CONTRIBUTING.md and dependabot.yml: a release is two weeks old before it's taken
QT_GROUP = ("pyqt6", "pyqt6-qt6")  # one release line between them, as PyQt6 6.11.0 with PyQt6-Qt6 6.11.2
HEADER = "# This file was autogenerated by uv via the following command:"
UNIVERSAL = ("--universal", "--generate-hashes")  # every lock here: each platform's packages, each with its hashes
CONSTRAINTS = "pins-constraints.txt"
DEV_EXTRA = "pyproject.toml (dev)"
EXIT_NOTHING, EXIT_ERROR, EXIT_MOVABLE = 0, 2, 3
MAX_ROUNDS = 6  # each round settles what the last one found; a handful is plenty
UV_TIMEOUT_S = 600


class Skip(NamedTuple):
    package: str
    version: str
    reason: str


# Releases nothing moves to, however old they get: one entry each, with its reason.
SKIP: tuple[Skip, ...] = (
    Skip("PyQt6", "6.12.0", "its own QtDBus.pyi has a syntax error that stops mypy before it reads anything, so every types job "
         "would fail; 6.12.1 fixes it (docs/delivery/m10-followups.md)"),
)


class PinsError(Exception):
    """Something this can't work around: the message says what, and uv's own words when uv failed."""


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


# -- versions, as PEP 440 orders them (the standard library has no parser for them)

_VERSION = re.compile(
    r"v?(?:(?P<epoch>\d+)!)?(?P<release>\d+(?:\.\d+)*)"
    r"(?:[-_.]?(?P<pre>alpha|beta|preview|pre|rc|a|b|c)[-_.]?(?P<pre_n>\d*))?"
    r"(?:-(?P<post_i>\d+)|[-_.]?(?P<post>post|rev|r)[-_.]?(?P<post_n>\d*))?"
    r"(?:[-_.]?(?P<dev>dev)[-_.]?(?P<dev_n>\d*))?"
    r"(?:\+[a-z0-9]+(?:[-_.][a-z0-9]+)*)?",
    re.IGNORECASE,
)
_PRE_RANK = {"a": 0, "alpha": 0, "b": 1, "beta": 1, "c": 2, "rc": 2, "pre": 2, "preview": 2}
VersionKey = tuple[int, tuple[int, ...], tuple[int, int, int], int, tuple[int, int]]


def version_key(version: str) -> VersionKey:
    match = _VERSION.fullmatch(version.strip())
    if not match:
        raise PinsError(f"not a version: {version!r}")
    release = [int(part) for part in match["release"].split(".")]
    while len(release) > 1 and release[-1] == 0:
        release.pop()
    post = match["post_i"] if match["post_i"] is not None else (match["post_n"] or "0") if match["post"] else None
    if match["pre"]:
        pre = (0, _PRE_RANK[match["pre"].lower()], int(match["pre_n"] or 0))
    else:
        pre = (-1, 0, 0) if match["dev"] and post is None else (1, 0, 0)  # 1.0.dev1 < 1.0a1 < 1.0
    dev = (0, int(match["dev_n"] or 0)) if match["dev"] else (1, 0)
    return int(match["epoch"] or 0), tuple(release), pre, -1 if post is None else int(post), dev


def release_line(version: str) -> tuple[int, int]:
    """6.11.2's line is 6.11."""
    match = _VERSION.fullmatch(version.strip())
    if not match:
        raise PinsError(f"not a version: {version!r}")
    parts = [int(part) for part in match["release"].split(".")] + [0]
    return parts[0], parts[1]


def older(versions: Iterable[str]) -> str:
    return min(versions, key=version_key)


# -- the lists: each .in file, its lock, and the command at the top of the lock


PIN = re.compile(r"(?P<name>[A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?)\s*(?P<extras>\[[^\]]*\])?\s*==\s*(?P<version>[^\s;#]+)"
                 r"\s*(?:;(?P<marker>[^#]*))?(?:#.*)?")
LOCKED = re.compile(r"(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)(?:\[[^\]]*\])?==(?P<version>[^\s;\\]+)")


@dataclass(frozen=True)
class Pin:
    name: str  # as the .in file writes it
    extras: str
    version: str
    marker: str  # its environment marker, without the ';': "sys_platform == 'win32'", or ""
    index: int  # its line in the file

    @property
    def key(self) -> str:
        return canonical(self.name)


@dataclass(frozen=True)
class InFile:
    path: Path
    lines: tuple[str, ...]
    pins: tuple[Pin, ...]
    includes: tuple[str, ...]  # the files it reads with -r


def read_in(path: Path) -> InFile:
    lines = tuple(path.read_text(encoding="utf-8").splitlines())
    pins, includes = [], []
    for index, raw in enumerate(lines):
        text = raw.split("#", 1)[0].strip()
        if not text:
            continue
        if text.startswith(("-r ", "--requirement ")):
            includes.append(text.split(None, 1)[1].strip())
        elif not text.startswith("-"):
            match = PIN.fullmatch(raw.strip())
            if not match:
                raise PinsError(f"{path.name}, line {index + 1}: every requirement here is pinned with ==, not {text!r}")
            pins.append(Pin(match["name"], match["extras"] or "", match["version"], (match["marker"] or "").strip(), index))
    return InFile(path, lines, tuple(pins), tuple(includes))


def loosen(infile: InFile) -> str:
    """The .in file with every pin's version taken off, and its environment marker kept; its other lines as they are."""
    lines = list(infile.lines)
    for pin in infile.pins:
        lines[pin.index] = pin.name + pin.extras + (f" ; {pin.marker}" if pin.marker else "")
    return "\n".join(lines) + "\n"


def read_lock(text: str) -> dict[str, str]:
    """A lock's versions by package. A package uv locked at two versions (one per platform) reads "1.0, 2.0"."""
    found: dict[str, list[str]] = {}
    for raw in re.sub(r"\\\r?\n", " ", text).splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        match = LOCKED.match(line)
        if not match:
            raise PinsError(f"not a pinned requirement: {line[:120]!r}")
        found.setdefault(canonical(match["name"]), []).append(match["version"])
    return {name: ", ".join(sorted(set(versions), key=version_key)) for name, versions in found.items()}


@dataclass(frozen=True)
class Header:
    args: tuple[str, ...]  # the command at the top of a lock, after `uv`


def output_of(args: Sequence[str]) -> str | None:
    for i, arg in enumerate(args):
        if arg in ("-o", "--output-file") and i + 1 < len(args):
            return args[i + 1]
        if arg.startswith("--output-file="):
            return arg.split("=", 1)[1]
    return None


def read_header(txt: Path, in_name: str) -> Header:
    """The command a lock was made with, from its first two lines: uv's universal lock, with hashes, of in_name."""
    lines = txt.read_text(encoding="utf-8").splitlines()[:2]
    if len(lines) < 2 or lines[0] != HEADER or not lines[1].startswith("#"):
        raise PinsError(f"{txt.name} has no uv header: lock it with the uv command CONTRIBUTING.md gives, not pip-compile")
    argv = shlex.split(lines[1].lstrip("#").strip())
    if argv[:3] != ["uv", "pip", "compile"]:
        raise PinsError(f"{txt.name}'s header isn't a `uv pip compile` command: {lines[1]}")
    args = tuple(argv[1:])
    if in_name not in args or output_of(args) != txt.name:
        raise PinsError(f"{txt.name}'s header doesn't lock {in_name} into {txt.name}, as a command run in packaging/ does: {lines[1]}")
    missing = [flag for flag in UNIVERSAL if flag not in args]
    if missing:
        raise PinsError(f"{txt.name}'s header has no {' '.join(missing)}: every lock here is uv's universal one, with hashes")
    return Header(args)


def compile_args(header: Header, cutoff: str, exempt: Iterable[str] = ()) -> list[str]:
    """The header's own command, with the cutoff in place of any it had, and the packages kept past it."""
    args: list[str] = []
    rest = iter(header.args)
    for arg in rest:
        if arg in ("--exclude-newer", "--exclude-newer-package"):
            next(rest, None)
        elif not arg.startswith(("--exclude-newer=", "--exclude-newer-package=")):
            args.append(arg)
    args += ["--exclude-newer", cutoff]
    for name in sorted(exempt):
        args += ["--exclude-newer-package", f"{name}=false"]
    return args


@dataclass(frozen=True)
class Lockfile:
    infile: InFile
    txt: Path
    header: Header
    current: dict[str, str]

    @property
    def stem(self) -> str:
        return self.txt.stem


def read_lists(packaging: Path) -> list[Lockfile]:
    lists = []
    for path in sorted(packaging.glob("requirements*.in")):
        txt = path.with_suffix(".txt")
        if not txt.is_file():
            raise PinsError(f"{path.name} has no lock beside it ({txt.name})")
        lists.append(Lockfile(read_in(path), txt, read_header(txt, path.name), read_lock(txt.read_text(encoding="utf-8"))))
    if not lists:
        raise PinsError(f"no requirements*.in in {packaging}")
    names = {lst.infile.path.name for lst in lists}
    for lst in lists:
        strays = set(lst.infile.includes) - names
        if strays:
            raise PinsError(f"{lst.infile.path.name} reads {sorted(strays)}, which isn't one of the lists here")
    return lists


def dev_extra(pyproject: Path) -> dict[str, str]:
    """pyproject.toml's dev extra: package -> its pinned version. CI's own versions, which it keeps in step with."""
    if not pyproject.is_file():
        return {}
    extra = tomllib.loads(pyproject.read_text(encoding="utf-8")).get("project", {}).get("optional-dependencies", {}).get("dev", [])
    pins = {}
    for requirement in extra:
        match = PIN.match(requirement)
        if match:
            pins[canonical(match["name"])] = match["version"]
    return pins


# -- uv


class Uv:
    def __init__(self, command: Sequence[str]) -> None:
        self.command = list(command)

    def run(self, args: Sequence[str], cwd: Path) -> str:
        try:
            done = subprocess.run([*self.command, *args], cwd=cwd, capture_output=True, text=True, encoding="utf-8",  # noqa: S603 - uv, with each lock's own command
                                  errors="replace", timeout=UV_TIMEOUT_S, check=False)
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise PinsError(f"uv {shlex.join(args)}: {exc}") from exc
        if done.returncode:
            raise PinsError(f"uv {shlex.join(args)} (in {cwd}) failed with exit {done.returncode}:\n{done.stderr.strip()}")
        return done.stdout

    def version(self) -> str:
        return " ".join(self.run(["--version"], Path.cwd()).split()[:2])


def find_uv(given: str | None) -> list[str]:
    found = shutil.which(given or "uv")
    if not found:
        raise PinsError("no uv on PATH: python -m pip install --require-hashes -r packaging/requirements-pins.txt")
    return [found]


# -- what can move


@dataclass(frozen=True)
class Hold:
    package: str  # canonical
    spec: str  # what every lock is held to: "==1.2", or "==6.11.*" for a release line
    why: str
    exempt: bool = False  # newer than the cutoff, so uv is told to look past it for this package


def constraints(holds: Mapping[str, Hold]) -> str:
    lines = [f"{skip.package}!={skip.version}" for skip in SKIP]
    lines += [f"{name}{hold.spec}" for name, hold in sorted(holds.items())]
    return "\n".join(lines) + "\n"


def resolve(lists: Sequence[Lockfile], uv: Uv, cutoff: str, holds: Mapping[str, Hold]) -> dict[str, str]:
    """Each list locked again by its own header's command, in a scratch folder, with every pin loosened: stem -> lock."""
    exempt = [name for name, hold in holds.items() if hold.exempt]
    with tempfile.TemporaryDirectory(prefix="chatmon-pins-") as scratch:
        work = Path(scratch)
        for lst in lists:
            (work / lst.infile.path.name).write_text(loosen(lst.infile), encoding="utf-8", newline="\n")
        (work / CONSTRAINTS).write_text(constraints(holds), encoding="utf-8", newline="\n")
        texts = {}
        for lst in lists:
            uv.run([*compile_args(lst.header, cutoff, exempt), "--constraints", CONSTRAINTS, "--quiet"], work)
            texts[lst.stem] = (work / lst.txt.name).read_text(encoding="utf-8")
    return texts


def single(version: str | None) -> bool:
    return version is not None and ", " not in version


def backwards(lists: Sequence[Lockfile], proposed: Mapping[str, Mapping[str, str]]) -> dict[str, Hold]:
    """Nothing moves backwards: a package locked now at a release newer than the cutoff keeps it."""
    holds = {}
    for lst in lists:
        for name, version in proposed[lst.stem].items():
            now = lst.current.get(name)
            if single(now) and single(version) and version_key(version) < version_key(str(now)):
                holds[name] = Hold(name, f"=={now}", f"stays at {now}, which is newer than the cutoff (the newest before it is {version}): "
                                   "nothing moves backwards", exempt=True)
    return holds


def qt_apart(lists: Sequence[Lockfile], proposed: Mapping[str, Mapping[str, str]]) -> dict[str, Hold]:
    """PyQt6 and PyQt6-Qt6 move together: when a lock would put them on two release lines, both take the older line."""
    holds = {}
    for lst in lists:
        versions = [proposed[lst.stem].get(name) for name in QT_GROUP]
        if not all(single(version) for version in versions):
            continue
        lines = {release_line(str(version)) for version in versions}
        if len(lines) > 1:
            major, minor = min(lines)
            for name in QT_GROUP:
                holds[name] = Hold(name, f"=={major}.{minor}.*", f"stays on the {major}.{minor} line with the rest of the Qt group "
                                   f"({', '.join(f'{n} {v}' for n, v in zip(QT_GROUP, versions, strict=True))} would split them): "
                                   "PyQt6 and PyQt6-Qt6 move together")
    return holds


def disagreements(proposed: Mapping[str, Mapping[str, str]]) -> dict[str, Hold]:
    """A package in more than one lock is at one version in all of them: where they'd differ, all take the older."""
    seen: dict[str, dict[str, str]] = {}
    for stem, lock in proposed.items():
        for name, version in lock.items():
            seen.setdefault(name, {})[stem] = version
    holds = {}
    for name, by in seen.items():
        if len(set(by.values())) > 1 and all(single(version) for version in by.values()):
            low = older(by.values())
            holds[name] = Hold(name, f"=={low}", f"held at {low} in every lock ({', '.join(f'{s}.txt {v}' for s, v in sorted(by.items()))}): "
                               "a package in more than one lock is at one version")
    return holds


@dataclass(frozen=True)
class Plan:
    cutoff: str
    uv: str
    lists: tuple[Lockfile, ...]
    texts: dict[str, str]  # stem -> the lock uv wrote
    proposed: dict[str, dict[str, str]]  # stem -> package -> version
    holds: dict[str, Hold]
    dev: dict[str, str]  # pyproject.toml's dev extra

    @property
    def exempt(self) -> list[str]:
        return sorted(name for name, hold in self.holds.items() if hold.exempt)

    def changed(self) -> list[Lockfile]:
        return [lst for lst in self.lists if self.proposed[lst.stem] != lst.current]


def make_plan(lists: Sequence[Lockfile], uv: Uv, cutoff: str, dev: Mapping[str, str]) -> Plan:
    holds: dict[str, Hold] = {}
    for _ in range(MAX_ROUNDS):
        texts = resolve(lists, uv, cutoff, holds)
        proposed = {stem: read_lock(text) for stem, text in texts.items()}
        found = {**disagreements(proposed), **qt_apart(lists, proposed), **backwards(lists, proposed)}
        if not found:
            return Plan(cutoff, uv.version(), tuple(lists), texts, proposed, holds, dict(dev))
        again = {name: hold for name, hold in found.items() if name not in holds}
        if not again:
            raise PinsError(f"held back already, but the locks still disagree about {', '.join(sorted(found))}")
        holds.update(again)
    raise PinsError(f"the locks didn't settle in {MAX_ROUNDS} rounds; held back so far: {', '.join(sorted(holds))}")


# -- the report


@dataclass(frozen=True)
class Change:
    key: str
    name: str
    current: str | None
    proposed: str | None
    locks: tuple[str, ...]
    pinned_in: tuple[str, ...]


def display_names(lists: Iterable[Lockfile]) -> dict[str, str]:
    return {pin.key: pin.name for lst in lists for pin in lst.infile.pins}


def changes(plan: Plan) -> list[Change]:
    names = display_names(plan.lists)
    rows: dict[tuple[str, str | None, str | None], list[str]] = {}
    for lst in plan.lists:
        new = plan.proposed[lst.stem]
        for key in sorted(lst.current.keys() | new.keys()):
            if lst.current.get(key) != new.get(key):
                rows.setdefault((key, lst.current.get(key), new.get(key)), []).append(lst.txt.name)
    found = []
    for (key, before, after), locks in rows.items():
        pinned_in = [lst.infile.path.name for lst in plan.lists if key in {pin.key for pin in lst.infile.pins}]
        pinned_in += [DEV_EXTRA] if key in plan.dev else []
        found.append(Change(key, names.get(key, key), before, after, tuple(locks), tuple(pinned_in)))
    return sorted(found, key=lambda change: (change.name.lower(), change.locks))


def table(rows: Sequence[Change], pinned: bool) -> list[str]:
    lines = ["| Package | Now | Proposed | Locks |" + (" Pinned in |" if pinned else ""),
             "| --- | --- | --- | --- |" + (" --- |" if pinned else "")]
    for row in rows:
        cells = [row.name, row.current or "(not locked)", row.proposed or "(dropped)", ", ".join(row.locks)]
        lines.append("| " + " | ".join(cells + ([", ".join(row.pinned_in)] if pinned else [])) + " |")
    return lines


def render(plan: Plan) -> str:
    found = changes(plan)
    pins = [change for change in found if change.pinned_in]
    others = [change for change in found if not change.pinned_in]
    lines = ["# Python pins ready to move" if found else "# Python pins: nothing to move", "",
             f"{plan.uv} locked each list in packaging/ again with every pin set free (its environment marker kept), "
             f"taking only releases uploaded before {plan.cutoff}, {COOLDOWN.days} days back. "
             + ("This is what would change." if found else "Every lock already holds what it would pick."), ""]
    if pins:
        lines += ["## Pins", "", *table(pins, pinned=True), ""]
    if others:
        lines += ["## Locked with them", "", *table(others, pinned=False), ""]
    lines += held_back(plan)
    if found:
        lines += moving(plan)
    lines += ["", "_packaging/pins.py wrote this; .github/workflows/pins.yml runs it every week and keeps one issue with "
              "its report while something can move._"]
    return "\n".join(lines) + "\n"


def held_back(plan: Plan) -> list[str]:
    locked = {name for lst in plan.lists for name in (*lst.current, *plan.proposed[lst.stem])}
    items = [f"- {skip.package} {skip.version} is skipped: {skip.reason}." for skip in SKIP if canonical(skip.package) in locked]
    names = display_names(plan.lists)
    items += [f"- {names.get(name, name)} {hold.why}." for name, hold in sorted(plan.holds.items())]
    return ["## Held back", "", *items, ""] if items else []


def moving(plan: Plan) -> list[str]:
    commands = [shlex.join(["uv", *compile_args(lst.header, plan.cutoff, plan.exempt)]) for lst in plan.changed()]
    return ["## Moving them", "",
            "Run this from the repository's root, then review the diff and commit it:", "",
            "```sh", f"python packaging/pins.py --apply --cutoff {plan.cutoff}", "```", "",
            "That moves each pin above in packaging/requirements*.in (and pyproject.toml's dev extra), then locks each list "
            "again in packaging/ with the command at the top of its .txt, the cutoff set:", "",
            "```sh", "cd packaging", *commands, "```", "",
            "Run by hand after moving the pins, these commands move only what the new pins need; --apply first hands uv "
            "the versions above, so it locks exactly this report."]


# -- moving them


def read_keeping(path: Path) -> tuple[str, str]:
    """A text file and its line ending, so it's written back the way it came."""
    data = path.read_bytes().decode("utf-8")
    return data.replace("\r\n", "\n"), "\r\n" if "\r\n" in data else "\n"


def write_keeping(path: Path, text: str, newline: str) -> None:
    path.write_bytes(text.replace("\n", newline).encode("utf-8"))


def moved_pins(infile: InFile, text: str, versions: Mapping[str, str]) -> str:
    lines = text.split("\n")
    for pin in infile.pins:
        new = versions.get(pin.key)
        if new is None:
            raise PinsError(f"{infile.path.name} pins {pin.name}, but its new lock doesn't have it")
        if new != pin.version:
            head = re.escape(pin.name) + r"\s*(?:\[[^\]]*\])?\s*==\s*"
            lines[pin.index] = re.sub(rf"^(\s*{head}){re.escape(pin.version)}", rf"\g<1>{new}", lines[pin.index], count=1)
    return "\n".join(lines)


def moved_dev_extra(text: str, versions: Mapping[str, str]) -> str:
    block = re.search(r"^dev = \[\n.*?^\]", text, re.MULTILINE | re.DOTALL)
    if not block:
        raise PinsError("pyproject.toml has no dev extra (dev = [ ... ]) to keep in step")

    def one(match: re.Match[str]) -> str:
        new = versions.get(canonical(match["name"]))
        return f'"{match["name"]}=={new}' if new else match[0]

    moved = re.sub(r'"(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)==(?P<version>[^";\s]+)', one, block[0])
    return text[:block.start()] + moved + text[block.end():]


def apply(plan: Plan, uv: Uv, root: Path) -> list[Path]:
    """Moves the pins and the dev extra, then locks each list that changes again with its own header's command (and
    the cutoff), in packaging/, after handing uv the report's versions in the lock it reads first. Every file is put
    back as it was if anything fails."""
    versions: dict[str, str] = {}
    for lst in plan.lists:
        for pin in lst.infile.pins:
            new = plan.proposed[lst.stem].get(pin.key)
            if new is not None and versions.setdefault(pin.key, new) != new:
                raise PinsError(f"{pin.name} would move to {versions[pin.key]} in one list and {new} in another")
    saved: dict[Path, bytes] = {}

    def change(path: Path, text: str, newline: str = "\n") -> None:
        saved.setdefault(path, path.read_bytes())
        write_keeping(path, text, newline)

    finished = False
    try:
        for lst in plan.lists:
            text, newline = read_keeping(lst.infile.path)
            moved = moved_pins(lst.infile, text, plan.proposed[lst.stem])
            if moved != text:
                change(lst.infile.path, moved, newline)
        pyproject = root / "pyproject.toml"
        if plan.dev:
            text, newline = read_keeping(pyproject)
            moved = moved_dev_extra(text, versions)
            if moved != text:
                change(pyproject, moved, newline)
        for lst in plan.changed():
            change(lst.txt, plan.texts[lst.stem])  # uv keeps the versions it finds in the lock it's writing
            uv.run([*compile_args(lst.header, plan.cutoff, plan.exempt), "--quiet"], lst.txt.parent)
            got = read_lock(lst.txt.read_text(encoding="utf-8"))
            wrong = {name: (got.get(name), want) for name, want in plan.proposed[lst.stem].items() if got.get(name) != want}
            extra = sorted(got.keys() - plan.proposed[lst.stem].keys())
            if wrong or extra:
                raise PinsError(f"{lst.txt.name} came out unlike the report: (locked, reported) {wrong}, and also locked {extra}")
        finished = True
    finally:
        if not finished:
            for path, data in saved.items():
                path.write_bytes(data)
    return sorted(saved)


# -- the command line


def cutoff_for(now: dt.datetime) -> str:
    """COOLDOWN before now, to the minute (rounded down, so every release it lets in is at least that old)."""
    return (now.astimezone(dt.UTC) - COOLDOWN).replace(second=0, microsecond=0).strftime("%Y-%m-%dT%H:%M:%SZ")


def parse_cutoff(text: str, now: dt.datetime) -> str:
    try:
        when = dt.datetime.fromisoformat(text)
    except ValueError as exc:
        raise PinsError(f"--cutoff {text}: not a date or an RFC 3339 time ({exc})") from exc
    if when.tzinfo is None:
        when = when.replace(tzinfo=dt.UTC)  # a bare date or time is UTC's
    if when > now - COOLDOWN:
        raise PinsError(f"--cutoff {text} is less than {COOLDOWN.days} days back: releases are at least that old before a pin moves to them")
    return when.astimezone(dt.UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def main(argv: Sequence[str] | None = None, *, uv: Sequence[str] | None = None, root: Path = ROOT, now: dt.datetime | None = None) -> int:
    parser = argparse.ArgumentParser(prog="pins.py", description=(__doc__ or "").split("\n\n", 1)[0])
    parser.add_argument("--apply", action="store_true", help="move the pins and lock each list again; review and commit after")
    parser.add_argument("--cutoff", help=f"take releases uploaded before this time (default: {COOLDOWN.days} days back, to the minute)")
    parser.add_argument("--report", type=Path, help="write the report here too")
    parser.add_argument("--uv", help="the uv to run (default: the one on PATH)")
    args = parser.parse_args(argv)
    now = now or dt.datetime.now(dt.UTC)
    try:
        cutoff = parse_cutoff(args.cutoff, now) if args.cutoff else cutoff_for(now)
        runner = Uv(uv or find_uv(args.uv))
        plan = make_plan(read_lists(root / "packaging"), runner, cutoff, dev_extra(root / "pyproject.toml"))
        report = render(plan)
        print(report, end="")
        if args.report:
            args.report.write_text(report, encoding="utf-8", newline="\n")
        if not args.apply:
            return EXIT_MOVABLE if plan.changed() else EXIT_NOTHING
        files = apply(plan, runner, root)
    except PinsError as exc:
        print(f"pins.py: {exc}", file=sys.stderr)
        return EXIT_ERROR
    done = ", ".join(path.relative_to(root).as_posix() for path in files)
    print(f"\nMoved: {done}. Review the diff, run the tests, and commit it." if files else "\nNothing to move.")
    return EXIT_NOTHING


if __name__ == "__main__":
    sys.exit(main())
