"""A stand-in for uv in tests/test_pins.py: `uv --version`, and `uv pip compile` over a made-up index, the JSON file
FAKE_UV_INDEX names: {"package": [{"version": "1.0", "uploaded": "2026-10-01T00:00:00Z", "requires": ["dep>=1"],
"python": ">=3.12"}]}. It honours what packaging/pins.py relies on: -r includes, environment markers, -o and the
versions already in that file (uv's preferences), --exclude-newer and --exclude-newer-package, -c constraints,
--python-version, and uv's header. With --universal it keeps every platform's packages, each with its marker;
without it, it locks for Linux alone, as pip-compile does, and drops the others. Each call is logged to the JSON
lines file FAKE_UV_LOG: its arguments, its folder, and the files it read."""

import datetime as dt
import hashlib
import json
import os
import sys
from pathlib import Path

from packaging.markers import Marker
from packaging.requirements import Requirement
from packaging.specifiers import SpecifierSet
from packaging.utils import canonicalize_name
from packaging.version import Version

HEADER = "# This file was autogenerated by uv via the following command:"
NOT_IN_HEADER = {"--quiet", "-q", "--upgrade", "-U", "--no-progress"}  # as uv leaves them out of its header
LINUX = {"sys_platform": "linux", "platform_system": "Linux", "os_name": "posix"}


def when(text):
    if text == "false":
        return None
    moment = dt.datetime.fromisoformat(text)
    return moment if moment.tzinfo else moment.replace(tzinfo=dt.UTC)


def options(argv):
    opts = {"inputs": [], "output": None, "cutoff": None, "exempt": {}, "constraints": [], "python": "3.14",
            "universal": False, "hashes": False, "upgrade": False}
    rest = iter(argv)
    for arg in rest:
        if arg in ("-o", "--output-file"):
            opts["output"] = next(rest)
        elif arg == "--exclude-newer":
            opts["cutoff"] = when(next(rest))
        elif arg == "--exclude-newer-package":
            name, _, date = next(rest).partition("=")
            opts["exempt"][canonicalize_name(name)] = when(date)
        elif arg in ("-c", "--constraints", "--constraint"):
            opts["constraints"].append(next(rest))
        elif arg == "--python-version":
            opts["python"] = next(rest)
        elif arg in ("--universal", "--generate-hashes", "--upgrade", "-U"):
            opts[{"--universal": "universal", "--generate-hashes": "hashes"}.get(arg, "upgrade")] = True
        elif arg in NOT_IN_HEADER:
            pass
        elif arg.startswith("-"):
            sys.exit(f"fake uv: no option {arg}")
        else:
            opts["inputs"].append(arg)
    return opts


def requirements(path, read):
    """Each requirement in a requirements file, with those of the files it reads with -r."""
    text = path.read_text(encoding="utf-8")
    read[path.name] = text
    found = []
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if line.startswith("-r "):
            found += [(req, label) for req, label in requirements(path.parent / line[3:].strip(), read)]
        elif line:
            found.append((Requirement(line), f"-r {path.name}"))
    return found


def candidates(name, spec, index, opts):
    cutoff = opts["exempt"][name] if name in opts["exempt"] else opts["cutoff"]
    for release in index.get(name, []):
        if cutoff is not None and when(release["uploaded"]) >= cutoff:
            continue
        if Version(opts["python"]) not in SpecifierSet(release.get("python", "")):
            continue
        if Version(release["version"]) in spec:
            yield release


def pick(name, spec, index, opts, preferred):
    found = list(candidates(name, spec, index, opts))
    if not found:
        sys.stderr.write(f"  x No solution found when resolving dependencies:\n  Because there is no version of {name}{spec} ...\n")
        sys.exit(1)
    for release in found:
        if release["version"] == preferred:
            return release
    return max(found, key=lambda release: Version(release["version"]))


def both(a, b):
    if a is None or b is None:
        return None  # wanted everywhere by one of them
    return a if a == b else f"({a}) or ({b})"


def resolve(roots, limits, index, opts, preferences):
    specs, markers, via, chosen = {}, {}, {}, {}
    pending = list(roots)
    while pending:
        req, label, parent = pending.pop(0)
        name = canonicalize_name(req.name)
        marker = str(req.marker) if req.marker else None
        marker = marker if parent is None else (parent if marker is None else f"({parent}) and ({marker})")
        if not opts["universal"] and marker and not Marker(marker).evaluate(LINUX):
            continue
        specs[name] = specs.get(name, SpecifierSet()) & req.specifier
        markers[name] = both(markers[name], marker) if name in markers else marker
        via.setdefault(name, set()).add(label)
        release = pick(name, specs[name] & limits.get(name, SpecifierSet()), index, opts, preferences.get(name))
        if chosen.get(name, {}).get("version") != release["version"]:
            chosen[name] = release
            pending += [(Requirement(dep), name, markers[name]) for dep in release.get("requires", [])]
    return chosen, markers, via


def lock(argv, chosen, markers, via, opts):
    lines = [HEADER, "#    uv " + " ".join(arg for arg in argv if arg not in NOT_IN_HEADER)]
    for name in sorted(chosen):
        version = chosen[name]["version"]
        marker = markers[name].replace('"', "'") if opts["universal"] and markers[name] else None  # uv quotes as '
        lines.append(f"{name}=={version}" + (f" ; {marker}" if marker else "") + (" \\" if opts["hashes"] else ""))
        if opts["hashes"]:
            lines.append(f"    --hash=sha256:{hashlib.sha256(f'{name}=={version}'.encode()).hexdigest()}")
        lines.append("    # via " + ", ".join(sorted(via[name])))
    return "\n".join(lines) + "\n"


def compile_(argv):
    opts = options(argv[2:])  # after `pip compile`
    index = {canonicalize_name(name): releases for name, releases in json.loads(Path(os.environ["FAKE_UV_INDEX"]).read_text(encoding="utf-8")).items()}
    read, limits = {}, {}
    for path in opts["constraints"]:
        for req, _ in requirements(Path(path), read):
            name = canonicalize_name(req.name)
            limits[name] = limits.get(name, SpecifierSet()) & req.specifier
    roots = [(req, label, None) for path in opts["inputs"] for req, label in requirements(Path(path), read)]
    output = Path(opts["output"])
    preferences = {}
    if output.exists() and not opts["upgrade"]:
        for raw in output.read_text(encoding="utf-8").splitlines():
            if "==" in raw and not raw.startswith((" ", "#")):
                name, _, rest = raw.partition("==")
                preferences[canonicalize_name(name)] = rest.split()[0]
    log({"argv": argv, "cwd": os.getcwd(), "read": read, "preferences": preferences})
    if os.environ.get("FAKE_UV_FAIL") == output.name and not opts["constraints"]:  # a lock --apply can't make
        sys.stderr.write(f"  x No solution found when resolving dependencies for {output.name}\n")
        sys.exit(1)
    chosen, markers, via = resolve(roots, limits, index, opts, preferences)
    output.write_text(lock(argv, chosen, markers, via, opts), encoding="utf-8", newline="\n")


def log(entry):
    with open(os.environ["FAKE_UV_LOG"], "a", encoding="utf-8") as f:
        f.write(json.dumps(entry) + "\n")


def main(argv):
    if argv == ["--version"]:
        print("uv 0.0.0 (fake)")
        return
    if argv[:2] != ["pip", "compile"]:
        sys.exit(f"fake uv: only `pip compile`, not {argv}")
    compile_(argv)


if __name__ == "__main__":
    main(sys.argv[1:])
